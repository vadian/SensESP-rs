use anyhow::{Result, bail};
use esp_idf_hal::peripherals::Peripherals;
use esp_idf_svc::eventloop::EspSystemEventLoop;
use log::info;
use sensesp::led::{Led, LedColor};
use sensesp::wifi::wifi;
use toml_cfg::toml_config;

#[derive(Debug)]
#[toml_config]
pub struct Config {
    #[default("")]
    wifi_ssid: &'static str,
    #[default("")]
    wifi_psk: &'static str,
}

fn main() -> Result<()> {
    // It is necessary to call this function once. Otherwise some patches to the runtime
    // implemented by esp-idf-sys might not link properly. See https://github.com/esp-rs/esp-idf-template/issues/71
    esp_idf_svc::sys::link_patches();

    // Bind the log crate to the ESP Logging facilities
    esp_idf_svc::log::EspLogger::initialize_default();

    let peripherals = Peripherals::take().unwrap();
    let sysloop = EspSystemEventLoop::take()?;

    log::info!("Hello, world!");

    // Initialize LED based on board type (selected via Cargo features)
    #[cfg(feature = "led-simple")]
    let mut led = {
        // ESP32 DevKit v1.0: Simple LED on GPIO2
        sensesp::led::SimpleLed::new(peripherals.pins.gpio2.into())?
    };

    #[cfg(feature = "led-ws2812")]
    let mut led = {
        // FireBeetle ESP32-E: WS2812 RGB LED on GPIO5
        sensesp::led::Ws2812Led::new(peripherals.pins.gpio5.into(), peripherals.rmt.channel0)?
    };

    // Start with yellow (or on for simple LED)
    led.set_color(LedColor::YELLOW)?;

    // The constant `CONFIG` is auto-generated by `toml_config`.
    let app_config = CONFIG;

    log::info!("{:#?}", CONFIG);

    // Connect to the Wi-Fi network
    let _wifi = match wifi(
        app_config.wifi_ssid,
        app_config.wifi_psk,
        peripherals.modem,
        sysloop,
        None,
    ) {
        Ok(inner) => inner,
        Err(err) => {
            // Red on error
            led.set_color(LedColor::RED)?;
            bail!("Could not connect to Wi-Fi network: {:?}", err)
        }
    };

    loop {
        // Blue
        led.set_color(LedColor::BLUE)?;
        std::thread::sleep(std::time::Duration::from_secs(1));
        info!("Hello, world!");

        // Green
        led.set_color(LedColor::GREEN)?;
        std::thread::sleep(std::time::Duration::from_secs(1));
    }
}
